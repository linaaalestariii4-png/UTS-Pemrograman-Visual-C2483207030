    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
        try {
    int total = Integer.parseInt(jTextField1.getText());
    int bayar = Integer.parseInt(txtBayar.getText());

    if (bayar < 0) {
        JOptionPane.showMessageDialog(this, "Uang pembayaran tidak boleh negatif!");
        return;
    }

    if (bayar < total) {
        JOptionPane.showMessageDialog(this, "Uang pembayaran kurang Rp" + (total - bayar));
        jTextField2.setText("");
        return;
    }

    int kembalian = bayar - total;
    jTextField2.setText(String.valueOf(kembalian));

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Hitung total dan masukkan uang pembayaran dengan angka!");
}
                                            

    }//GEN-LAST:event_btnBayarActionPerformed

